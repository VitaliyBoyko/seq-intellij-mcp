/** Opt-in: uses the production client and writes only uniquely tagged synthetic events. */
class SeqCloudIntegrationTest {
    private lateinit var baseUri: URI
    private lateinit var readKey: String
    private lateinit var ingestKey: String
    private lateinit var http: HttpClient
    private lateinit var client: SeqApiClient

    @Before
    fun setUp() {
        val url = requiredEnvironment("SEQ_TEST_SERVER_URL").trimEnd('/') + "/"
        baseUri = URI(url)
        val localHttp = System.getenv("SEQ_TEST_ALLOW_LOCAL_HTTP") == "true" &&
                baseUri.scheme.equals("http", ignoreCase = true) && baseUri.host in setOf("localhost", "127.0.0.1", "[::1]")
        require(
            (baseUri.scheme.equals("https", ignoreCase = true) || localHttp) && baseUri.host != null &&
                    baseUri.rawUserInfo == null && baseUri.rawQuery == null && baseUri.rawFragment == null
        ) { "SEQ_TEST_SERVER_URL must be an HTTPS base URL. Local loopback HTTP requires SEQ_TEST_ALLOW_LOCAL_HTTP=true." }
        readKey = requiredEnvironment("SEQ_TEST_API_KEY")
        ingestKey = requiredEnvironment("SEQ_TEST_INGEST_API_KEY")
        http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5)).apply {
            System.getenv("SEQ_TEST_CA_CERT")?.takeIf(String::isNotBlank)?.let { certificatePath ->
                val certificates = Files.newInputStream(Path.of(certificatePath)).use {
                    CertificateFactory.getInstance("X.509").generateCertificates(it)
                }
                require(certificates.isNotEmpty()) { "SEQ_TEST_CA_CERT must contain a trusted test CA certificate" }
                val trustStore = KeyStore.getInstance(KeyStore.getDefaultType()).apply {
                    load(null, null)
                    certificates.forEachIndexed { index, certificate ->
                        setCertificateEntry(
                            "test-ca-$index",
                            certificate
                        )
                    }
                }
                val managers = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
                    .apply { init(trustStore) }
                sslContext(SSLContext.getInstance("TLS").apply { init(null, managers.trustManagers, null) })
            }
        }.build()
        client = SeqApiClient({ url }, { readKey }, http)
    }

    @After
    fun tearDown() {
        if (::http.isInitialized) http.shutdownNow()
    }

    @Test(timeout = 90_000)
    fun authenticatedSearchAndSqlFindTheSameSyntheticEvent() = runBlocking {
        val marker = UUID.randomUUID().toString()
        val from = Instant.now().minusSeconds(60)
        ingest(marker)
        val capabilities = client.getCapabilities()
        assertEquals("api_key", capabilities.authContext.authMode)
        assertTrue("Event query capability failed: ${capabilities.notes.joinToString()}", capabilities.canQueryEvents)

        // Ingestion can complete before the event becomes visible to a query.
        val events = withTimeout(30_000) {
            var result = client.searchEvents(searchRequest(marker, from))
            while (result.isEmpty()) {
                delay(500)
                result = client.searchEvents(searchRequest(marker, from))
            }
            result
        }
        assertEquals("Expected exactly the event generated by this test", 1, events.size)
        assertNotNull("Search must return an event id", events.single().jsonObject["Id"])

        val query = SeqSqlQueryRequest(
            query = "select count(*) as Matches from stream where McpSmokeId = '$marker'",
            rangeStartUtc = from,
            timeoutSeconds = 15,
        )
        val result = client.querySql(query)
        assertNull("Seq returned a SQL error", result["Error"])
        assertEquals("1", result["Rows"]!!.jsonArray.single().jsonArray.single().jsonPrimitive.content)

        val csv = client.querySqlCsv(query).lineSequence()
            .map { it.trim().removePrefix("\uFEFF").removeSurrounding("\"") }
            .filter(String::isNotEmpty)
            .toList()
        assertEquals("CSV must return the same count as JSON", listOf("Matches", "1"), csv)
    }

    @Test(timeout = 45_000)
    fun liveWebSocketCapturesNewSyntheticEvents() = runBlocking {
        val marker = UUID.randomUUID().toString()
        val capture = async { client.waitForEvents("McpSmokeId = '$marker'", 1, null) }
        // Repeated emission avoids a race between HTTP ingestion and the WebSocket handshake.
        val producer = launch {
            repeat(20) {
                ingest(marker)
                delay(500)
            }
        }
        try {
            val events = capture.await()
            assertEquals("No live event arrived; check WebSocket proxying and ingestion permissions", 1, events.size)
            assertNotNull(events.single().jsonObject["Id"])
        } finally {
            producer.cancelAndJoin()
            capture.cancelAndJoin()
        }
    }

    @Test(timeout = 45_000)
    fun invalidCredentialsAreRejected() = runBlocking {
        val invalid = SeqApiClient({ baseUri.toString() }, { "invalid-${UUID.randomUUID()}" }, http)
        try {
            invalid.searchEvents(SeqSearchRequest("", count = 1, timeoutSeconds = 5))
            fail("The remote Seq server accepted an invalid API key; enable authentication for this test environment")
        } catch (error: SeqApiException) {
            assertTrue("Expected HTTP 401 or 403 for an invalid key", error.statusCode in listOf(401, 403))
        }
    }

    private fun searchRequest(marker: String, from: Instant) = SeqSearchRequest(
        filter = "McpSmokeId = '$marker' and McpSmokeText = 'a&b+c/%'",
        count = 10,
        fromDateUtc = from,
        timeoutSeconds = 10,
    )

    private suspend fun ingest(marker: String) = runInterruptible(Dispatchers.IO) {
        val event = buildJsonObject {
            put("@t", Instant.now().toString())
            put("@mt", "Seq MCP cloud integration test {McpSmokeId}")
            put("McpSmokeId", marker)
            put("McpSmokeText", "a&b+c/%")
            put("Application", "seq-mcp-integration-tests")
        }
        val request = HttpRequest.newBuilder(baseUri.resolve("api/events/raw?clef"))
            .timeout(Duration.ofSeconds(15))
            .header("X-Seq-ApiKey", ingestKey)
            .header("Content-Type", "application/vnd.serilog.clef")
            .POST(HttpRequest.BodyPublishers.ofString("$event\n"))
            .build()
        val response = http.send(request, HttpResponse.BodyHandlers.discarding())
        assertTrue("Test event ingestion failed (HTTP ${response.statusCode()})", response.statusCode() in 200..299)
    }

    private fun requiredEnvironment(name: String): String =
        System.getenv(name)?.takeIf(String::isNotBlank)
            ?: error("Set $name before running cloudIntegrationTest; see README.md. No cloud tests are skipped silently.")
}
